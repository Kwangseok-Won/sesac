s = "0123456789"
print(s[::2])
print(s[1::2])
# 간격을 -1로 주면 문자열이 거꾸로 뒤집힙니다. 아주 자주 쓰는 관용구예요.
print(s[::-1])    # 거꾸로 → 9876543210

# 심화 — 슬라이싱은 범위를 넘어도 에러가 안 난다
#
# 인덱싱 s[10]은 범위를 벗어나면 IndexError로 죽지만, 슬라이싱 s[2:100]은 있는 만큼만 잘라주고 조용히 넘어갑니다.
# 또 시작·끝을 비우면 각각 "처음부터"·"끝까지"를 뜻해요 — s[:3]은 앞 3글자, s[3:]은 3번부터 끝까지.
# "인덱싱은 한 글자(범위 넘으면 에러), 슬라이싱은 구간(넘쳐도 안전)"으로 구분해 기억하면 헷갈리지 않습니다.
print(s[:10])


