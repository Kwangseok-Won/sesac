# 심화 — 진리값(truthy / falsy): 초보자의 함정
#
# 파이썬의 if는 True/False만 받는 게 아닙니다. 모든 값을 참·거짓으로 판단해요.
# 그런데 "빈 것"과 "0"은 거짓(falsy)으로 취급됩니다
# — 0, 0.0, ""(빈 문자열), [](빈 리스트), None이 대표적이에요.
# 그 외의 값(0이 아닌 숫자, 내용이 있는 문자열·리스트)은 모두 참(truthy)입니다.
# 그래서 if name:는 "name이 빈 문자열이 아니면"이라는 뜻으로 자주 쓰입니다.
# 반대로 초보자는 if score == 0:을 쓸 자리에 if score:를 써서 "0점"을 놓치기도 해요
# — 0은 falsy라서 조건이 거짓이 되거든요. "빈 것/0은 거짓"이라는 규칙을 기억하면
# 이 함정을 피할 수 있습니다.

is_rain = False

if is_rain:
    print("우산을 챙기세요!")

print("외출합니다")
