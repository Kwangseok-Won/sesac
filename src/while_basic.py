# while — 조건이 참인 동안
# for가 "정해진 횟수"라면, while은 "조건이 참인 동안 계속"입니다. 몇 번 반복할지 미리 모를 때 써요.
#
# 가장 무서운 실수 — 무한루프
# count = count + 1을 빠뜨리면 count가 영원히 1이라 조건이 계속 참 → 프로그램이 멈추지 않습니다.
# while True:도 조건이 항상 참이라 무한루프예요. while을 쓸 땐 "이 반복이 언제 끝나는가"를 반드시 확인하세요. (위 코드에서 마지막 줄을 지우고 실행하면 브라우저가 멈출 수 있으니 주의!)

count = 1
while count <= 5:
    print(f"{count}번째")
    count += 1 # 이걸 빠뜨리면 무한루프!

print(count)
print("끝")
