# 심화 — 왜 b = a는 복사가 아닐까?
#
# 02장에서 "변수는 값을 담는 상자가 아니라, 값에 붙이는 이름표"라고 했죠.
# b = a는 값을 복사하는 게 아니라, a가 가리키던 그 리스트에 b라는 이름표를 하나 더 붙이는 것뿐입니다.
# 그래서 이름은 둘이지만 실제 리스트는 하나예요.
# b.append(4)로 그 하나뿐인 리스트를 고치면, 같은 것을 보고 있던 a로 읽어도 당연히 바뀐 값이 나옵니다.
#
# 숫자·문자열에서 이 함정이 없는 이유도 같습니다.
# x = 3; y = x; y = y + 1은 3을 4로 고치는 게 아니라 y가
# 새 값 4로 이름표를 옮기는 것이라 x는 그대로 3이에요 — 불변객체는 애초에 고칠 수가 없으니까요.
# 그래서 원본을 지키려면 항상 .copy()로 별개의 리스트를 먼저 만드는 습관을 들이세요.

a = [1, 2, 3]
b = a.copy()     # 진짜 복사 (별개의 리스트)

b.append(4)
print(a)          # [1,2,3] — a는 안전!
print(b)          # [1,2,3,4]
