# assert를 함수 검증에 써봅시다. 방법은 단순해요
# — 이 입력을 넣으면 이 값이 나와야 한다는 쌍을 여러 개 적는 겁니다.
# 8장의 add 함수를 여러 입력으로 검사해 볼게요.

# 네 개의 assert가 모두 통과했으니 마지막 print가 실행됩니다.
# 이제 함수를 실수로 return a - b로 바꿔 보세요
# — 첫 줄부터 바로 에러가 나며, 어디가 틀렸는지 즉시 알 수 있습니다.
# 이렇게 검사 코드를 곁에 두면, 함수를 고칠 때마다 안전망이 생겨요.

# 왜 여러 케이스인가
# — add(2, 3) == 5 하나만 통과했다고 함수가 옳다고 할 순 없어요.
# 함수가 그냥 return 5(무조건 5 반환)여도 그 하나는 우연히 통과하니까요.
# 하지만 add(0, 0) == 0을 넣는 순간 정체가 드러나죠.
# 서로 다른 입력을 여러 개 걸수록 우연한 통과가 걸러집니다.
# 테스트는 많을수록 촘촘한 그물이 돼요.


def add(a: int, b: int):
    return a + b


# 입력 → 기대출력 쌍으로 검사
assert add(2, 3) == 5
assert add(0, 0) == 0
assert add(-1, 1) == 0
assert add(100, 200) == 300
print("add 함수: 4개 케이스 모두 통과 ✓")
